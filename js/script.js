// შეცვალოს ენა
function setLanguage(language) {
  if (!translations[language]) {
    return;
  }

  document.documentElement.lang = language;

  // ჩვეულებრივი ტექსტების თარგმნა
  document.querySelectorAll("[data-i18n]").forEach((element) => {
    const key = element.dataset.i18n;
    const translatedText = translations[language][key];

    if (translatedText !== undefined) {
      element.textContent = translatedText;
    }
  });

  // Placeholder ტექსტების თარგმნა
  document.querySelectorAll("[data-i18n-placeholder]").forEach((element) => {
    const key = element.dataset.i18nPlaceholder;
    const translatedText = translations[language][key];

    if (translatedText !== undefined) {
      element.placeholder = translatedText;
    }
  });

  // არჩეული ენის ღილაკის მონიშვნა
  document.querySelectorAll("[data-lang]").forEach((button) => {
    const isActive = button.dataset.lang === language;

    button.classList.toggle("active", isActive);
    button.setAttribute("aria-pressed", String(isActive));
  });

  // ენის შენახვა
  try {
    localStorage.setItem("luxe-language", language);
  } catch (error) {
    // ენა მაინც შეიცვლება, თუ localStorage მიუწვდომელია.
  }
}

// ენის ღილაკებზე მოვლენების დამატება
document.querySelectorAll("[data-lang]").forEach((button) => {
  button.addEventListener("click", () => {
    setLanguage(button.dataset.lang);
  });
});

// ბოლო არჩეული ენის აღდგენა
let savedLanguage = "en";

try {
  const storedLanguage = localStorage.getItem("luxe-language");

  if (storedLanguage && translations[storedLanguage]) {
    savedLanguage = storedLanguage;
  }
} catch (error) {
  // ნაგულისხმევი ენა იქნება ინგლისური.
}

setLanguage(savedLanguage);
